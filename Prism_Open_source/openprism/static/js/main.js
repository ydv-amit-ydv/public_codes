async function addToLayout(g) {
  if (!P().layouts.length) { const L = createLayout(); P().layouts.push(L); }
  const lid = P().layouts.length === 1 ? P().layouts[0].id : await layoutPicker();
  if (!lid) return;
  const L = getLayout(lid);
  const n = L.items.length;
  L.items.push({ id: uid('i'), type: 'graph', graphId: g.id, x: 20 + (n % 2) * 500, y: 20 + Math.floor(n / 2) * 380, w: Math.min(480, g.style.width), h: Math.min(360, g.style.height), z: n + 1 });
  commit('Add to layout');
  open('layout', lid);
}

function exportTableCSV(t) {
  const info = TABLE_TYPES[t.type];
  const head = ['Row title'];
  if (info.hasX) head.push(t.xTitle || 'X');
  t.datasets.forEach((d) => { for (let k = 0; k < (d.reps || 1); k++) head.push(d.reps > 1 ? `${d.name} Y${k + 1}` : d.name); });
  const q = (s) => (/[",\n]/.test(s) ? `"${String(s).replace(/"/g, '""')}"` : s);
  const lines = [head.map(q).join(',')];
  t.cells.forEach((row, r) => {
    if (row.every((v) => v === '') && !t.x[r] && !t.rowLabels[r]) return;
    lines.push([t.rowLabels[r], ...(info.hasX ? [t.x[r]] : []), ...row].map((v) => q(v ?? '')).join(','));
  });
  download(`${t.name}.csv`, lines.join('\n'), 'text/csv');
}

