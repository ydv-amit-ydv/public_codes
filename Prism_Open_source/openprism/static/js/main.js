document.addEventListener('keydown', (e) => {
  const mod = e.ctrlKey || e.metaKey;
  const inField = ['INPUT', 'TEXTAREA', 'SELECT'].includes(e.target.tagName) || e.target.isContentEditable;
  if (mod && e.key.toLowerCase() === 'z' && !inField) { e.preventDefault(); if (e.shiftKey) doRedo(); else doUndo(); }
  else if (mod && e.key.toLowerCase() === 'y' && !inField) { e.preventDefault(); doRedo(); }
  else if (mod && e.key.toLowerCase() === 's') { e.preventDefault(); saveToServer({ saveAs: e.shiftKey }); }
  else if (mod && e.key.toLowerCase() === 'o') { e.preventDefault(); projectBrowser(); }
  else if (mod && e.key.toLowerCase() === 't') { e.preventDefault(); newTableDialog(); }
  else if (mod && e.shiftKey && e.key.toLowerCase() === 'p') { e.preventDefault(); openPalette(); }
  else if (mod && e.key.toLowerCase() === 'k') { e.preventDefault(); doAnalyze(currentTable()); }
  else if (mod && e.key.toLowerCase() === 'g') { e.preventDefault(); const t = currentTable(); if (t) newGraphFor(t); }
  else if (mod && e.key.toLowerCase() === 'l') { e.preventDefault(); newLayout(); }
  else if (e.key === 'F2' && !inField && state.current?.kind !== 'table') { e.preventDefault(); renameCurrent(); }
  else if (e.key === 'F1') { e.preventDefault(); openManual(contextTopic()); }
});

