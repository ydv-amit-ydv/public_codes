async function doAnalyze(t, preset) {
  if (!t) { toast('Select a data table first', 'err'); return; }
  const choice = await analyzeDialog(t, preset);
  if (!choice) return;
  status('Analyzing…');
  const a = await createAnalysis(t, choice.key, choice.params);
  // like Prism: overlay fits / significance on the table's graphs automatically
  if (a.result?.overlay) {
    P().graphs.filter((g) => g.tableId === t.id && (a.result.overlay.kind !== 'plot' || g.kind === 'analysis-plot')).forEach((g) => {
      const kinds = (g.analysisIds || []).map((id) => getAnalysis(id)?.result?.overlay?.kind);
      if (!kinds.includes(a.result.overlay.kind)) g.analysisIds = [...(g.analysisIds || []), a.id];
      else g.analysisIds = (g.analysisIds || []).filter((id) => getAnalysis(id)?.result?.overlay?.kind !== a.result.overlay.kind).concat(a.id);
      if (a.result.overlay.kind === 'curves' && a.params.plotBand) g.style.showBand = true;
      if (a.key === 'roc') g.kind = g.kind === 'roc' ? 'roc' : g.kind;
    });
    if (a.result.overlay.kind === 'plot' && PLOT_ANALYSES.has(a.key)) {
      const g = createGraph(t, 'analysis-plot');
      g.name = uniqueName(P().graphs, a.name);
      g.analysisIds = [a.id];
      Object.assign(g.style, { title: '', xTitle: '', yTitle: '', showLegend: true, plotIndex: 0 });
      P().graphs.push(g);
    }
    if (a.key === 'roc') { const g = createGraph(t, 'roc'); g.name = uniqueName(P().graphs, `ROC of ${t.name}`); g.analysisIds = [a.id]; g.style.title = 'ROC curve'; g.style.xTitle = '100% - Specificity%'; g.style.yTitle = 'Sensitivity%'; P().graphs.push(g); }
  }
  commit('Analyze');
  status(a.error ? `Analysis failed: ${a.error}` : 'Analysis complete');
  open('analysis', a.id);
}

async function editAnalysis(a) {
  const t = getTable(a.tableId);
  if (!t) return;
  const choice = await analyzeDialog(t, a.key, a);
  if (!choice) return;
  a.params = choice.params;
  await rerun(a);
}
async function rerun(a) {
  await runAnalysis(a);
  commit('Re-run');
  open('analysis', a.id);
}

function newGraphFor(t) {
  const g = createGraph(t);
  g.analysisIds = P().analyses.filter((a) => a.tableId === t.id && a.result?.overlay && a.key !== 'roc').map((a) => a.id).slice(-2);
  P().graphs.push(g);
  commit('New graph');
  open('graph', g.id);
}

