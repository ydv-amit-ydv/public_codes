/** Add or edit a calculated column: a formula of other data sets (by letter), with a live preview. */
function formulaDialog(t, index = null) {
  const ds = index != null ? t.datasets[index] : null;
  const name = h('input', { type: 'text', value: ds ? ds.name : 'Calculated', maxlength: 80 });
  const formula = h('input', { type: 'text', value: ds?.formula || '', placeholder: 'e.g. (B - A) / A * 100   or   log10(C)', spellcheck: 'false', style: { fontFamily: 'var(--mono)', width: '100%' } });
  const preview = h('div', { class: 'formula-preview' });
  const legend = t.datasets.map((d, i) => (i === index ? null : h('span', { class: 'chip', onclick: () => { formula.value += letter(i); formula.focus(); upd(); } }, `${letter(i)} = ${d.name}`)));
  function upd() {
    preview.innerHTML = '';
    try {
      const { f, refs } = compile(formula.value);
      if (!refs.length) throw new Error('Use at least one data set letter.');
      const rows = [];
      for (let r = 0; r < t.cells.length && rows.length < 6; r++) {
        const env = {}; let ok = true;
        for (const ref of refs) {
          const j = t.datasets.findIndex((_, k) => letter(k) === ref);
          if (j < 0 || j === index) throw new Error(`There is no data set ${ref}.`);
          const v = String(t.cells[r]?.[colOffset(t, j)] ?? '').trim();
          if (v === '' || Number.isNaN(Number(v))) { ok = false; break; }
          env[ref] = Number(v);
        }
        if (ok) rows.push([r + 1, ...refs.map((x) => env[x]), f(env)]);
      }
      preview.append(h('table', { class: 'rtable' }, h('thead', {}, h('tr', {}, h('th', {}, 'Row'), ...refs.map((x) => h('th', {}, x)), h('th', {}, 'Result'))),
        h('tbody', {}, rows.map((r) => h('tr', {}, r.map((c) => h('td', { class: 'num' }, typeof c === 'number' ? String(Number(c.toPrecision(10))) : c)))))));
      if (!rows.length) preview.append(h('p', { class: 'hint' }, 'No rows with values yet.'));
    } catch (e) { preview.append(h('div', { class: 'errbox' }, e.message)); }
  }
  formula.addEventListener('input', upd);
  upd();
  modal({ title: ds ? `Formula of “${ds.name}”` : 'Add calculated column', wide: true,
    body: h('div', {},
      h('p', { class: 'hint' }, 'Refer to data sets by their letters. Operators + − × (*) ÷ (/) ^ and functions log10, ln, log2, exp, sqrt, abs, round, min, max, pow, logit, sin, cos… The column is recalculated whenever the data change; its cells cannot be edited directly.'),
      h('div', { class: 'field' }, h('label', {}, 'Column name'), name),
      h('div', { class: 'field' }, h('label', {}, 'Formula'), formula),
      h('div', { class: 'chip-row' }, ...legend), h('h4', {}, 'Preview'), preview),
    buttons: [{ label: 'Cancel' }, { label: ds ? 'Update' : 'Add column', primary: true, onClick: () => {
      try {
        const { refs } = compile(formula.value);
        if (!refs.length) throw new Error('Use at least one data set letter.');
        const used = refs.map((x) => t.datasets.findIndex((_, k) => letter(k) === x));
        if (used.some((j) => j < 0 || j === index)) throw new Error('The formula refers to a data set that does not exist.');
        if (ds) { ds.formula = formula.value.trim(); ds.name = name.value.trim() || ds.name; }
        else {
          const reps = Math.max(...used.map((j) => t.datasets[j].reps || 1));
          t.datasets.push({ name: name.value.trim() || 'Calculated', reps, formula: formula.value.trim() });
          t.cells.forEach((row) => row.push(...Array(reps).fill('')));
        }
        recompute(t);
        normalizeTable(t);
        t.rev++;
        commit(ds ? 'Edit formula' : 'Add calculated column');
        open('table', t.id);
        return true;
      } catch (e) { toast(e.message, 'err'); return false; }
    } }] });
}
