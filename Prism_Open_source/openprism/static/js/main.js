function fitRibbon() {
  const r = document.getElementById('ribbon');
  if (!r.clientWidth) return;  // not visible yet (sign-in screen): the resize observer fits it once shown
  const modes = ribbonMode === 'auto' ? ['full', 'compact', 'icons'] : [ribbonMode];
  for (const m of modes) {
    r.dataset.mode = m;
    if (r.scrollWidth <= r.clientWidth + 1) break;
  }
  r.classList.toggle('overflowing', r.scrollWidth > r.clientWidth + 1);
}
let ribbonW = 0;
new ResizeObserver(() => {
  const w = document.getElementById('ribbon').clientWidth;
  if (Math.abs(w - ribbonW) > 2) { ribbonW = w; fitRibbon(); }
}).observe(document.getElementById('ribbon'));

function contextTopic() {
  const c = state.current;
  if (!c) return 'getting-started';
  if (c.kind === 'table') return `table-${getTable(c.id)?.type}`;
  if (c.kind === 'analysis') { const k = getAnalysis(c.id)?.key; return HELP[k] ? k : 'results'; }
  if (c.kind === 'graph') return 'graph-type';
  if (c.kind === 'layout') return 'layouts';
  return 'projects';
}

