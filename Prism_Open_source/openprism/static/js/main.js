// Menus that do not fit move into a "More ▾" menu; full keyboard use: F10 opens the
// first menu, ←/→ switch menus, ↑/↓ move, Enter runs, Esc closes.
function drawMenus() {
  const bar = document.getElementById('menubar');
  bar.innerHTML = '';
  const all = MENUS();
  const make = (name, itemsFn) => {
    const m = h('div', { class: 'menu' });
    const list = h('div', { class: 'menu-list', role: 'menu' });
    const fill = () => {
      list.innerHTML = '';
      for (const it of itemsFn()) {
        if (it === '-') { list.append(h('hr')); continue; }
        if (it.sub) { list.append(h('div', { class: 'menu-sub' }, it.sub)); continue; }
        const [label, fn, key, disabled] = it;
        list.append(h('button', { role: 'menuitem', disabled: !!disabled, onclick: () => { closeMenus(); fn(); } }, h('span', {}, label), key ? h('kbd', {}, key) : null));
      }
    };
    const openIt = (focusFirst) => {
      closeMenus();
      fill(); m.classList.add('open'); placeMenu(list, btn);
      if (focusFirst) list.querySelector('button:not([disabled])')?.focus();
    };
    const btn = h('button', { 'aria-haspopup': 'true', onclick: (e) => { e.stopPropagation(); if (m.classList.contains('open')) closeMenus(); else openIt(e.detail === 0); },
      onmouseenter: () => { if (document.querySelector('.menu.open') && !m.classList.contains('open')) openIt(false); },
      onkeydown: (e) => { if (e.key === 'ArrowDown') { e.preventDefault(); openIt(true); } } }, name);
    m.openIt = openIt;
    m.append(btn, list);
    list.addEventListener('keydown', (e) => menuKeys(e, m));
    return m;
  };
  const menus = all.map(([name, items]) => make(name, () => all.find((x) => x[0] === name)?.[1] || items));
  menus.forEach((m) => bar.append(m));
  // overflow: move trailing menus into "More"
  const hidden = [];
  while (bar.scrollWidth > bar.clientWidth + 1 && menus.length - hidden.length > 2) {
    const i = menus.length - 1 - hidden.length;
    hidden.unshift(i);
    menus[i].remove();
    if (!bar.querySelector('.menu-more')) bar.append(moreMenu());
  }
  function moreMenu() {
    const m = make('More ▾', () => hidden.flatMap((i) => [{ sub: all[i][0] }, ...all[i][1], '-']).slice(0, -1));
    m.classList.add('menu-more');
    return m;
  }
  if (hidden.length && !bar.querySelector('.menu-more')) bar.append(moreMenu());
}
