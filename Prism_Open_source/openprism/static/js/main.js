function itemMenu(e, kind, id) {
  const items = [{ label: 'Open', action: () => open(kind, id) }, { label: 'Rename…', action: () => { state.current = { kind, id }; renameCurrent(); } },
    { label: 'Duplicate', action: () => duplicate(kind, id) }];
  if (kind === 'table') items.push('-', { label: 'Analyze…', action: () => doAnalyze(getTable(id)) }, { label: 'New graph', action: () => newGraphFor(getTable(id)) });
  if (kind === 'graph') items.push('-', { label: 'Add to layout…', action: () => addToLayout(getGraph(id)) });
  items.push('-', { label: 'Delete', action: () => deleteItem(kind, id) });
  contextMenu(e.clientX, e.clientY, items);
}

function duplicate(kind, id) {
  const pr = P();
  const list = { table: pr.tables, analysis: pr.analyses, graph: pr.graphs, layout: pr.layouts }[kind];
  const src = list.find((x) => x.id === id);
  const c = JSON.parse(JSON.stringify(src));
  c.id = uid(kind[0]);
  c.name = uniqueName(list, `${src.name} copy`);
  if (kind === 'analysis') delete c.outputIds;
  list.push(c);
  commit('Duplicate');
  open(kind, c.id);
}

async function deleteItem(kind, id) {
  const pr = P();
  const obj = { table: getTable, analysis: getAnalysis, graph: getGraph, layout: getLayout }[kind](id);
  if (!obj) return;
  let msg = `Delete “${obj.name}”?`;
  if (kind === 'table') {
    const deps = pr.analyses.filter((a) => a.tableId === id).length + pr.graphs.filter((g) => g.tableId === id).length;
    if (deps) msg += ` Its ${deps} linked analyses and graphs will also be deleted.`;
  }
  if (kind === 'table') {
    const gids = pr.graphs.filter((g) => g.tableId === id).map((g) => g.id);
    pr.tables = pr.tables.filter((t) => t.id !== id);
    pr.analyses = pr.analyses.filter((a) => a.tableId !== id);
    pr.graphs = pr.graphs.filter((g) => g.tableId !== id);
    pr.layouts.forEach((l) => { l.items = l.items.filter((it) => !gids.includes(it.graphId)); });
  } else if (kind === 'analysis') {
    pr.analyses = pr.analyses.filter((a) => a.id !== id);
    pr.graphs.forEach((g) => { g.analysisIds = (g.analysisIds || []).filter((x) => x !== id); });
  } else if (kind === 'graph') {
    pr.graphs = pr.graphs.filter((g) => g.id !== id);
    pr.layouts.forEach((l) => { l.items = l.items.filter((it) => it.graphId !== id); });
  } else if (kind === 'layout') pr.layouts = pr.layouts.filter((l) => l.id !== id);
  commit('Delete');
  if (state.current?.id === id) open(null);
  else drawNav();
  toast(msg.replace(/^Delete “(.*)”\?/, 'Deleted “$1”.').replace(' will also be deleted.', ' were deleted too.'), '', { label: 'Undo', onClick: doUndo });
}

