function menuKeys(e, m) {
  const items = [...m.querySelectorAll('.menu-list button:not([disabled])')];
  const i = items.indexOf(document.activeElement);
  const menus = [...document.querySelectorAll('#menubar .menu')];
  const mi = menus.indexOf(m);
  if (e.key === 'ArrowDown') { e.preventDefault(); items[(i + 1) % items.length]?.focus(); }
  else if (e.key === 'ArrowUp') { e.preventDefault(); items[(i - 1 + items.length) % items.length]?.focus(); }
  else if (e.key === 'ArrowRight' || e.key === 'ArrowLeft') { e.preventDefault(); const n = menus[(mi + (e.key === 'ArrowRight' ? 1 : -1) + menus.length) % menus.length]; n?.openIt(true); }
  else if (e.key === 'Escape') { e.preventDefault(); closeMenus(); m.querySelector(':scope > button')?.focus(); }
  else if (e.key === 'Home') { e.preventDefault(); items[0]?.focus(); }
  else if (e.key === 'End') { e.preventDefault(); items[items.length - 1]?.focus(); }
}
